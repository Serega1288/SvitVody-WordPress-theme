function build_po(string $pot, string $locale, array $translations): string {
    $blocks = preg_split('/\R{2,}/', trim($pot));
    foreach ($blocks as &$block) {
        if (!preg_match('/^msgid "(.*)"$/m', $block, $match) || '' === $match[1]) { continue; }
        $msgid = stripcslashes($match[1]);
        $translated = $translations[$msgid] ?? $msgid;
        $block = preg_replace('/^msgstr ""$/m', 'msgstr "' . addcslashes($translated, "\\\"") . '"', $block, 1);
    }
    $po = implode("\n\n", $blocks) . "\n";
    return preg_replace('/"Language-Team: LANGUAGE <LL@li.org>\\n"/', '"Language-Team: ' . $locale . '\\n"\n"Language: ' . $locale . '\\n"', $po, 1);
}

